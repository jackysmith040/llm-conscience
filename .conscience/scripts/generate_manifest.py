#!/usr/bin/env python3
"""
Generates .conscience/skills.toml from installed skills; preserves the external ledger.
"""
from datetime import date
from pathlib import Path

skills_dir = Path(".conscience/skills")
output_file = Path(".conscience/skills.toml")
EXTERNAL_MARKER = "# >>> EXTERNAL DEPENDENCIES (preserved by generator) <<<"
skill_names = sorted(p.name for p in skills_dir.iterdir() if p.is_dir())
count = len(skill_names)

domains = {
    "planning": [
        "same-wavelength",
        "grill",
        "to-spec",
        "to-tickets",
        "wayfinder",
        "architect",
        "prototype",
        "route",
        "icm-architect",
    ],
    "engineering": [
        "senior-stable-delivery",
        "pipeline",
        "rabit-auditor",
        "review",
        "recover",
        "git-workflow",
        "git-mode",
        "vibesec",
        "ponytail",
        "browser",
        "implement-spec",
    ],
    "craft": [
        "impeccable",
        "i-am-impeccable",
        "refactoring-ui",
        "color-palette",
        "emil-design-eng",
        "imprint",
        "nothing-design",
        "review-animations",
        "favicon-gen",
        "applying-brand-guidelines",
    ],
    "clarity": [
        "caveman",
        "ste-writing",
        "remember",
        "session-handoff",
        "the-basis",
        "retro",
        "skill-creator",
        "autopoiesis",
        "pace",
    ],
    "motion": [
        "gsap-plugins",
        "motion-first-learning",
        "visual-learning-software",
        "playground-builder",
        "excalidraw-diagram",
        "mermaid-visualizer",
        "beautiful-article",
    ],
    "specialized": [
        "financial-analysis",
        "stock-analysis",
        "excel-generator",
        "systematic-research",
        "graphify-ide",
    ],
}


def get_domain(name):
    for d, members in domains.items():
        if name in members:
            return d
    return "specialized"


def clean_desc(raw):
    raw = raw.strip().replace('"', "'")
    lines = [l.strip().lstrip(">-").lstrip(">").strip() for l in raw.splitlines() if l.strip()]
    cleaned = " ".join(lines)
    return cleaned[:140] if cleaned else "Specialized agent capability"


header = f"""# ==============================================================================
# Conscience OS Skills Registry (skills.toml)
# Internal capability registry + external dependency ledger.
# Generated by .conscience/scripts/generate_manifest.py — external block preserved.
# ==============================================================================

[manifest]
version = "3.1.0"
last_updated = "{date.today().isoformat()}"
total_skills = {count}

[domains]
planning = "High-level discovery, specifications, decision mapping, and architectural breakdown"
engineering = "Production code delivery, testing, stability, security, and refactoring"
craft = "UI/UX design, visual engineering, tactile feedback, and anti-slop styling"
clarity = "Token compression, clean prose, session continuity, and conceptual study"
motion = "Interactive widgets, animations, diagrams, and visual simulations"
specialized = "Domain-specific tools for finance, spreadsheets, research, and graph extraction"

"""

body = ""

for name in skill_names:
    skill_folder = skills_dir / name
    skill_file = skill_folder / "SKILL.md"
    desc = "Specialized agent capability"

    if skill_file.is_file():
        content = skill_file.read_text(encoding="utf-8", errors="ignore")
        if "description:" in content:
            raw_desc = content.split("description:")[1].split("---")[0]
            desc = clean_desc(raw_desc)

    dom = get_domain(name)
    body += f"[skills.{name}]\n"
    body += f'domain = "{dom}"\n'
    body += f'trigger = "/{name}"\n'
    body += f'summary = "{desc}"\n'
    body += "installed = true\n\n"

external = ""
if output_file.is_file():
    existing = output_file.read_text(encoding="utf-8", errors="ignore")
    if EXTERNAL_MARKER in existing:
        external = existing[existing.index(EXTERNAL_MARKER):]

output_file.write_text(header + body + external, encoding="utf-8")
print(f"[*] Generated {output_file} with {count} skills (external ledger preserved).")
